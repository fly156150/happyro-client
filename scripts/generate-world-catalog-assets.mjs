import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import sharp from 'sharp';

const projectRoot = path.resolve(import.meta.dirname, '..');
const sourceDirectory = path.resolve(
	projectRoot,
	process.env.NPC_IMAGE_SOURCE || '../happyro-api/resources/game-data/world/npcs'
);
const outputDirectory = path.resolve(projectRoot, 'applications/pwa/data/world');
const mapImageDirectory = path.resolve(
	projectRoot,
	process.env.MAP_IMAGE_SOURCE || '../happyro-api/resources/game-data/world/maps'
);
const npcCatalogSource = path.resolve(
	projectRoot,
	process.env.NPC_CATALOG_SOURCE || '../happyro-api/resources/game-data/world/npc-catalog.json'
);
const npcInstanceOutput = path.resolve(projectRoot, 'applications/pwa/data/navigation/npc-instances.json');
const clientResourceManifest = path.resolve(
	projectRoot,
	process.env.CLIENT_RESOURCE_MANIFEST || '../../work/grf-extract/kro-20211105/data/manifest.json'
);
const serverMapConfig = path.resolve(
	projectRoot,
	process.env.SERVER_MAP_CONFIG || '../happyro-server/conf/maps_athena.conf'
);
const supportedMapOutput = path.resolve(projectRoot, 'src/DB/Map/SupportedMapTable.js');
const tileSize = 112;
const contentSize = 104;
const columns = 16;
const rows = 16;
const entriesPerSheet = columns * rows;

async function generateSupportedMapTable() {
	const resourceManifestContents = await fs.readFile(clientResourceManifest, 'utf8');
	const serverMapConfigContents = await fs.readFile(serverMapConfig, 'utf8');
	const resourceManifest = JSON.parse(resourceManifestContents);
	const resourceExtensions = new Map();
	for (const file of resourceManifest.files || []) {
		const match = String(file.path || '').match(/^data\/([^/]+)\.(rsw|gat|gnd)$/i);
		if (!match) continue;
		const mapName = match[1].toLocaleLowerCase();
		if (!resourceExtensions.has(mapName)) resourceExtensions.set(mapName, new Set());
		resourceExtensions.get(mapName).add(match[2].toLocaleLowerCase());
	}
	const clientMaps = new Set(
		[...resourceExtensions]
			.filter(([, extensions]) => ['rsw', 'gat', 'gnd'].every(extension => extensions.has(extension)))
			.map(([mapName]) => mapName)
	);
	const serverMaps = new Set(
		[...serverMapConfigContents.matchAll(/^\s*map:\s*([a-z0-9_@-]+)\s*$/gim)].map(match =>
			match[1].toLocaleLowerCase()
		)
	);
	const supportedMaps = [...clientMaps].filter(mapName => serverMaps.has(mapName)).sort();
	const formattedMaps = supportedMaps.map(mapName => `\t'${mapName}'`).join(',\n');
	const source = `// Generated by scripts/generate-world-catalog-assets.mjs. Do not edit manually.\n// Client manifest SHA256: ${crypto.createHash('sha256').update(resourceManifestContents).digest('hex')}\n// Server map config SHA256: ${crypto.createHash('sha256').update(serverMapConfigContents).digest('hex')}\nconst SupportedMapTable = new Set([\n${formattedMaps}\n]);\n\nexport function isSupportedMapResource(mapName) {\n\tconst normalized = String(mapName || '')\n\t\t.replace(/\\.(?:rsw|gat)$/i, '')\n\t\t.toLocaleLowerCase();\n\treturn SupportedMapTable.has(normalized);\n}\n\nexport default SupportedMapTable;\n`;
	await fs.writeFile(supportedMapOutput, source);
	return { clientCount: clientMaps.size, serverCount: serverMaps.size, supportedCount: supportedMaps.length };
}

const imageFiles = (await fs.readdir(sourceDirectory))
	.filter(file => /^\d+\.png$/.test(file))
	.sort((left, right) => Number.parseInt(left, 10) - Number.parseInt(right, 10));
const sourceHash = crypto.createHash('sha256');
for (const file of imageFiles) sourceHash.update(await fs.readFile(path.join(sourceDirectory, file)));
const mapImages = (await fs.readdir(mapImageDirectory))
	.filter(file => file.endsWith('.png'))
	.map(file => file.slice(0, -4).toLocaleLowerCase())
	.sort();
const mapImagesHash = crypto.createHash('sha256').update(mapImages.join('\n')).digest('hex');
const supportedMaps = await generateSupportedMapTable();

const npcCatalog = JSON.parse(await fs.readFile(npcCatalogSource, 'utf8'));
if (npcCatalog.schema !== 'happyro-npc-catalog/v1' || !Array.isArray(npcCatalog.entries)) {
	throw new Error('Shared NPC catalog has an unsupported schema');
}
const npcInstances = {};
for (const entry of npcCatalog.entries) {
	if (!/[\u3400-\u9fff]/.test(entry.display_name)) continue;
	const position = `${entry.map}:${entry.x}:${entry.y}`;
	if (!npcInstances[position]) npcInstances[position] = { name: entry.display_name, sourceName: entry.source_name };
}

const sortedNpcInstances = Object.fromEntries(
	Object.entries(npcInstances).sort(([left], [right]) => left.localeCompare(right))
);
// Shipped as a fetched data file rather than a bundled module: the table is
// ~780 KB and only the navigation search needs it.
await fs.mkdir(path.dirname(npcInstanceOutput), { recursive: true });
await fs.writeFile(
	npcInstanceOutput,
	`${JSON.stringify({ schemaVersion: 1, instances: sortedNpcInstances })}\n`
);

await fs.rm(outputDirectory, { recursive: true, force: true });
await fs.mkdir(outputDirectory, { recursive: true });

const sprites = {};
for (let sheet = 0; sheet * entriesPerSheet < imageFiles.length; sheet += 1) {
	const files = imageFiles.slice(sheet * entriesPerSheet, (sheet + 1) * entriesPerSheet);
	const composites = await Promise.all(
		files.map(async (file, tile) => {
			const resized = await sharp(path.join(sourceDirectory, file))
				.resize(contentSize, contentSize, { fit: 'inside', withoutEnlargement: true, kernel: 'nearest' })
				.png()
				.toBuffer({ resolveWithObject: true });
			const column = tile % columns;
			const row = Math.floor(tile / columns);
			sprites[Number.parseInt(file, 10)] = { atlas: sheet, tile };
			return {
				input: resized.data,
				left: column * tileSize + Math.floor((tileSize - resized.info.width) / 2),
				top: row * tileSize + Math.floor((tileSize - resized.info.height) / 2)
			};
		})
	);

	await sharp({
		create: {
			width: columns * tileSize,
			height: rows * tileSize,
			channels: 4,
			background: { r: 0, g: 0, b: 0, alpha: 0 }
		}
	})
		.composite(composites)
		.webp({ lossless: true, effort: 6 })
		.toFile(path.join(outputDirectory, `npc-atlas-${sheet}.webp`));
}

const manifest = {
	schema: 'happyro-world-assets/v3',
	source: {
		sha256: sourceHash.digest('hex'),
		npcDefinitionsSha256: npcCatalog.content_sha256,
		npcCatalogVersion: npcCatalog.version,
		mapImagesSha256: mapImagesHash,
		imageCount: imageFiles.length
	},
	atlas: { tileSize, columns, rows },
	sprites,
	mapImages
};
await fs.writeFile(path.join(outputDirectory, 'npc-assets.json'), `${JSON.stringify(manifest)}\n`);
process.stdout.write(
	`Generated ${imageFiles.length} NPC images in ${Math.ceil(imageFiles.length / entriesPerSheet)} atlases, ${mapImages.length} map image references, ${Object.keys(npcInstances).length} localized instance names, and ${supportedMaps.supportedCount} supported maps (${supportedMaps.clientCount} client, ${supportedMaps.serverCount} server).\n`
);
